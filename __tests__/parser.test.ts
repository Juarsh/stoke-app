import golden from '../src/data/golden.json';
import dev from '../src/data/dev-meals.json';
import { parser } from '../src/parser';

describe('TS parser == Go parser (golden outputs generated by scripts/sync-dishes.sh)', () => {
  it.each((golden as { in: string; out: unknown }[]).map((g) => [g.in, g.out]))('%s', (input: unknown, out: unknown) => {
    // Go marshals an empty (nil) slice as null; the TS port always returns []
    const o = out as { items: unknown[] | null };
    expect(parser.parse(input as string)).toEqual({ ...o, items: o.items ?? [] });
  });
});

describe('dev samples expectations (same check as Go TestDevMeals)', () => {
  it.each((dev as unknown as { meals: { in: string; want: [string, number][] }[] }).meals.map((m) => [m.in, m.want]))('%s', (input: unknown, want: unknown) => {
    // Go TestDevMeals compares quantities with a 0.011 tolerance
    const got = parser.parse(input as string).items;
    const w = want as [string, number][];
    expect(got.map((i) => i.dish_id)).toEqual(w.map((x) => x[0]));
    got.forEach((i, k) => expect(Math.abs(i.quantity - w[k][1])).toBeLessThanOrEqual(0.011));
  });
});

describe('parser behaviour', () => {
  it('is fast (<100ms offline)', () => {
    const t = Date.now();
    for (let i = 0; i < 100; i++) parser.parse('2 roti dal sabzi thoda ghee aur 1 katori rajma chawal');
    expect((Date.now() - t) / 100).toBeLessThan(100);
  });
  it('edit recomputes from table for that item only', () => {
    const [roti] = parser.parse('2 roti').items;
    const e = parser.edit(roti, { quantity: 3 });
    expect(e.kcal.best).toBe(330);
    const [dal] = parser.parse('dal').items;
    expect(parser.edit(dal, { oil: 'less' }).kcal.best).toBeLessThan(dal.kcal.best);
  });
});
